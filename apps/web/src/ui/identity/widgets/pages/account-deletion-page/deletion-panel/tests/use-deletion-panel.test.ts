import { act, renderHook } from '@testing-library/react'
import { describe, expect, it } from 'vitest'
import { useDeletionPanel } from '../use-deletion-panel'

describe('useDeletionPanel', () => {
  it('discards all preparation when the deletion tab unmounts', () => {
    const first = renderHook(() => useDeletionPanel())
    act(() => first.result.current.handleOpenChange(true))
    act(() => first.result.current.handleCurrentPasswordChange('discard-me'))
    act(() => first.result.current.handleConfirmationChange(true))
    act(() => first.result.current.handleTogglePasswordVisibility())
    first.unmount()
    const second = renderHook(() => useDeletionPanel())
    expect(second.result.current.isOpen).toBe(false)
    expect(second.result.current.currentPassword).toBe('')
    expect(second.result.current.hasConfirmed).toBe(false)
    expect(second.result.current.isPasswordVisible).toBe(false)
  })
  it('clears password, consent and visibility on close and reopens empty', () => {
    const { result } = renderHook(() => useDeletionPanel())
    expect(result.current.isOpen).toBe(false)
    expect(result.current.currentPassword).toBe('')
    expect(result.current.hasConfirmed).toBe(false)
    expect(result.current.isPasswordVisible).toBe(false)
    act(() => result.current.handleOpenChange(true))
    act(() => result.current.handleCurrentPasswordChange('local-secret'))
    act(() => result.current.handleConfirmationChange(true))
    act(() => result.current.handleTogglePasswordVisibility())
    expect(result.current.isOpen).toBe(true)
    expect(result.current.currentPassword).toBe('local-secret')
    expect(result.current.hasConfirmed).toBe(true)
    expect(result.current.isPasswordVisible).toBe(true)
    act(() => result.current.handleTogglePasswordVisibility())
    expect(result.current.isPasswordVisible).toBe(false)
    act(() => result.current.handleConfirmationChange(false))
    expect(result.current.hasConfirmed).toBe(false)
    act(() => result.current.handleConfirmationChange(true))
    act(() => result.current.handleTogglePasswordVisibility())
    act(() => result.current.handleOpenChange(false))
    expect(result.current.isOpen).toBe(false)
    expect(result.current.currentPassword).toBe('')
    expect(result.current.hasConfirmed).toBe(false)
    expect(result.current.isPasswordVisible).toBe(false)
    act(() => result.current.handleOpenChange(true))
    expect(result.current.currentPassword).toBe('')
    expect(result.current.hasConfirmed).toBe(false)
  })
})
